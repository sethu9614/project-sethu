import 'dotenv/config';
import express from 'express';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
import User from './models/User.js';
import SecurityEvent from './models/SecurityEvent.js';
import { requireAuth } from './middleware/auth.js';
import { threatDetector } from './middleware/threatDetector.js';

const app = express();
const PORT = process.env.PORT || 5000;

if (!process.env.JWT_SECRET || process.env.JWT_SECRET.length < 32) {
  console.error('JWT_SECRET must be set to a random string of at least 32 characters.');
  process.exit(1);
}

app.set('trust proxy', 1);
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_ORIGIN || 'http://localhost:5173' }));
app.use(express.json({ limit: '20kb' }));
app.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 200, standardHeaders: 'draft-7', legacyHeaders: false }));
app.use(threatDetector);

app.get('/api/health', (_req, res) => res.json({ status: 'ok', service: 'Webpage Defense API' }));

function validEmail(email) {
  return typeof email === 'string' && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) && email.length <= 254;
}

app.post('/api/auth/signup', async (req, res) => {
  try {
    const { name, email, password } = req.body || {};
    if (typeof name !== 'string' || name.trim().length < 2 || name.trim().length > 80 ||
        !validEmail(email) || typeof password !== 'string' || password.length < 10 || password.length > 128) {
      return res.status(400).json({ message: 'Enter a name, valid email, and password (10–128 characters).' });
    }
    const normalizedEmail = email.toLowerCase().trim();
    if (await User.findOne({ email: normalizedEmail })) {
      return res.status(409).json({ message: 'An account with that email already exists.' });
    }
    const user = await User.create({
      name: name.trim(),
      email: normalizedEmail,
      passwordHash: await bcrypt.hash(password, 12)
    });
    const token = jwt.sign({ email: user.email }, process.env.JWT_SECRET, { subject: user.id, expiresIn: '2h' });
    res.status(201).json({ token, user: { name: user.name, email: user.email } });
  } catch (error) {
    if (error.code === 11000) return res.status(409).json({ message: 'An account with that email already exists.' });
    console.error(error);
    res.status(500).json({ message: 'Unable to create account.' });
  }
});

app.post('/api/auth/login', async (req, res) => {
  try {
    const { email, password } = req.body || {};
    if (!validEmail(email) || typeof password !== 'string') {
      return res.status(400).json({ message: 'Enter a valid email and password.' });
    }
    const user = await User.findOne({ email: email.toLowerCase().trim() });
    if (!user || !(await bcrypt.compare(password, user.passwordHash))) {
      await SecurityEvent.create({
        type: 'Failed login', severity: 'medium', message: 'A login attempt failed',
        path: '/api/auth/login', method: 'POST', action: 'logged', sourceIp: req.ip || 'unknown'
      });
      return res.status(401).json({ message: 'Invalid email or password.' });
    }
    const token = jwt.sign({ email: user.email }, process.env.JWT_SECRET, { subject: user.id, expiresIn: '2h' });
    res.json({ token, user: { name: user.name, email: user.email } });
  } catch (error) {
    console.error(error);
    res.status(500).json({ message: 'Unable to sign in.' });
  }
});

app.get('/api/dashboard/summary', requireAuth, async (_req, res) => {
  try {
    const [totalEvents, blocked, highSeverity, recent] = await Promise.all([
      SecurityEvent.countDocuments(),
      SecurityEvent.countDocuments({ action: 'blocked' }),
      SecurityEvent.countDocuments({ severity: 'high' }),
      SecurityEvent.find().sort({ createdAt: -1 }).limit(1).lean()
    ]);
    res.json({
      totalEvents,
      blockedRequests: blocked,
      highSeverityAlerts: highSeverity,
      systemStatus: 'Protected',
      lastEventAt: recent[0]?.createdAt || null
    });
  } catch {
    res.status(500).json({ message: 'Unable to load dashboard metrics.' });
  }
});

app.get('/api/events', requireAuth, async (_req, res) => {
  try {
    const events = await SecurityEvent.find().sort({ createdAt: -1 }).limit(50).lean();
    res.json({ events });
  } catch {
    res.status(500).json({ message: 'Unable to load security events.' });
  }
});

app.post('/api/demo-alert', requireAuth, async (_req, res) => {
  try {
    const event = await SecurityEvent.create({
      type: 'Demo threat simulation',
      severity: 'high',
      message: 'Test alert generated by the dashboard; no attack was performed.',
      path: '/demo/simulation',
      method: 'GET',
      action: 'blocked',
      sourceIp: '127.0.0.1',
      demo: true
    });
    res.status(201).json({ event });
  } catch {
    res.status(500).json({ message: 'Unable to create demo alert.' });
  }
});

app.use((_req, res) => res.status(404).json({ message: 'Route not found' }));

async function start() {
  try {
    await mongoose.connect(process.env.MONGO_URI || 'mongodb://127.0.0.1:27017/webpage_defense');
    app.listen(PORT, () => console.log(`Webpage Defense API listening on http://localhost:${PORT}`));
  } catch (error) {
    console.error('MongoDB connection failed:', error.message);
    process.exit(1);
  }
}
start();
